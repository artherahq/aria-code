def register_markdown_pdf_tools(tool_registry: Dict, schema_registry: List) -> int:
    if not HAS_MARKDOWN:
        return 0
    added = 0
    if "export_markdown_pdf" not in tool_registry:
        tool_registry["export_markdown_pdf"] = (
            tool_export_markdown_pdf,
            "Markdown 报告 → 专业排版 PDF（中英双语模板）",
        )
        added += 1
    existing = {s.get("function", {}).get("name") for s in schema_registry}
    for schema in MARKDOWN_PDF_TOOL_SCHEMAS:
        if schema["function"]["name"] not in existing:
            schema_registry.append(schema)
    return added
