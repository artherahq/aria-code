"""
markdown_pdf.py — Markdown 报告 → 印刷级排版 HTML/PDF（中英双语模板）
=====================================================================
与 report_generator.py（HTML 研报引擎）互补：本模块面向**Markdown 交付物**
（/report --format md 的投研报告、分析纪要、任何模型生成的 md 文本），
渲染成专业浅色印刷模板后走 report_generator.export_pdf 引擎链出 PDF。

模板特性（与 Arthera research 渲染管线同源）:
  · 真表格：深色列头、斑马纹、跨页重复表头（thead）
  · 信号徽章着色：买入/BUY 绿 · 减仓/REDUCE 琥珀 · 卖出/SELL 红 · 持有/HOLD 灰
  · 首个引用块升级为元信息条（生成时间 | 数据截止 …）
  · 打印分页规则：@page A4、表格行不跨页断裂、章节标题不孤行
  · lang="zh" / "en" 切换模板文案（页脚、免责声明）；"auto" 按内容检测

PDF 分页取决于引擎：headless Chrome（推荐，完整 @page 支持）；
macOS WebKit 兜底为单长页（内容完整，无分页）。

对外:
  render_markdown_html(md_text, lang="auto", title=None) -> str
  markdown_to_pdf(md_text_or_path, pdf_path, lang="auto") -> Optional[Path]
  tool_export_markdown_pdf(params) + register_markdown_pdf_tools(...)
"""

