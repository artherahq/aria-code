def detect_lang(md_text: str) -> str:
    """内容含 CJK 字符占比 > 5% 判为中文。"""
    if not md_text:
        return "en"
    cjk = sum(1 for ch in md_text[:4000] if "一" <= ch <= "鿿")
    return "zh" if cjk > len(md_text[:4000]) * 0.05 else "en"


def _apply_badges(html: str) -> str:
    def _decorate_cell(m: re.Match) -> str:
        cell = m.group(0)
        for pat, fg, bg in _BADGES:
            cell = re.sub(
                rf"((?:🟢|🟡|🔴|⬜|✅|⚠️|➖)?\s*(?:<strong>)?(?:{pat})(?:</strong>)?)",
                rf'<span class="badge" style="color:{fg};background:{bg}">\1</span>',
                cell, count=1,
            )
        return cell
    return re.sub(r"<td>.*?</td>", _decorate_cell, html, flags=re.S)


def _fit_wide_tables(html: str) -> str:
    """≥12 列 → t-xwide (6.8pt)；≥9 列 → t-wide (7.5pt)：按边界自适应字号。"""
    def _tag(m: re.Match) -> str:
        table = m.group(0)
        head = table.split("</tr>", 1)[0]
        n = len(re.findall(r"<th[ >]", head))
        if n >= 12:
            cls = "t-xwide"
        elif n >= 9:
            cls = "t-wide"
        else:
            return table
        return re.sub(r"<table>", f'<table class="{cls}">', table, count=1)
    return re.sub(r"<table>.*?</table>", _tag, html, flags=re.S)


def _promote_meta_bar(html: str) -> str:
    return re.sub(
        r"(</h1>\s*)<blockquote>(.*?)</blockquote>",
        lambda m: m.group(1) + '<div class="meta">'
                  + re.sub(r"</?p>", "", m.group(2)).replace("|", "·")
                  + "</div>",
        html, count=1, flags=re.S,
    )


def render_markdown_html(md_text: str, lang: str = "auto",
                         title: Optional[str] = None) -> str:
    """Markdown 文本 → 完整可打印 HTML 文档（浅色印刷模板）。"""
    if not HAS_MARKDOWN:
        raise RuntimeError("python-markdown 未安装: pip install markdown")
    if lang == "auto":
        lang = detect_lang(md_text)
    labels = _LABELS.get(lang, _LABELS["en"])

    body = _markdown.markdown(
        md_text, extensions=["tables", "sane_lists", "nl2br", "fenced_code"],
        output_format="html5",
    )
    body = _promote_meta_bar(body)
    body = _apply_badges(body)
    body = _fit_wide_tables(body)

    if not title:
        m = re.search(r"<h1[^>]*>(.*?)</h1>", body, re.S)
        title = re.sub(r"<[^>]+>", "", m.group(1)) if m else "Report"
    footer = (f"{labels['footer']} · {datetime.now():%Y-%m-%d %H:%M} · "
              f"{labels['disclaimer']}")
    return (
        f'<!doctype html><html lang="{lang}"><head><meta charset="utf-8">'
        f"<title>{title}</title><style>{_CSS}</style></head>"
        f'<body><div class="page">{body}'
        f'<div class="footer">{footer}</div></div></body></html>'
    )


def markdown_to_pdf(md: str | Path, pdf_path: Path,
                    lang: str = "auto") -> Optional[Path]:
    """Markdown（文本或 .md 路径）→ 排版 PDF。返回 PDF 路径，失败 None。"""
    md_text = (Path(md).read_text(encoding="utf-8")
               if isinstance(md, Path) or (isinstance(md, str)
                   and len(md) < 512 and Path(md).expanduser().is_file())
               else str(md))
    html = render_markdown_html(md_text, lang=lang)
    from aria_code.report_generator import html_string_to_pdf
    return html_string_to_pdf(html, Path(pdf_path))


# ── Agent 工具 ───────────────────────────────────────────────────────────────

def tool_export_markdown_pdf(params: Dict[str, Any]) -> Dict[str, Any]:
    """LOCAL_TOOLS 入口。params: {markdown|md_path, filename?, lang?}"""
    try:
        md = params.get("markdown") or params.get("md_path")
        if not md:
            return {"success": False, "error": "缺少 markdown 或 md_path"}
        lang = params.get("lang", "auto")
        stem = str(params.get("filename") or "report").removesuffix(".pdf")
        try:
            from aria_code.artifacts import create_user_artifact
            record = create_user_artifact("reports", params.get("topic"),
                                          stem, ".pdf")
            pdf_path = record.path
        except Exception:
            pdf_path = Path.cwd() / f"{stem}.pdf"
        source = Path(md) if (isinstance(md, str) and len(md) < 512
                              and Path(md).expanduser().is_file()) else md
        out = markdown_to_pdf(source, pdf_path, lang=lang)
        if out is None:
            return {"success": False,
                    "error": "无可用 PDF 引擎（安装 Chrome/Edge，"
                             "或 macOS: pip install pyobjc-framework-WebKit）"}
        return {"success": True, "path": str(out),
                "size_kb": out.stat().st_size // 1024,
                "lang": lang if lang != "auto" else detect_lang(
                    md if isinstance(md, str) else Path(md).read_text(encoding="utf-8")[:4000])}
    except Exception as exc:
        logger.debug("[md-pdf] export error: %s", exc, exc_info=True)
        return {"success": False, "error": str(exc)}


